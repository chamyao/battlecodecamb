"""Generate sim/src/constants_gen.cpp from an engine constants dump: oracle/fixtures/engine2_constants.json (engine 2.0.0,
cambc 4.0.0; CBS_FIXTURE overrides, e.g. engine_constants.json for engine 1.0.3)."""
import json, os, struct
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FIX = os.environ.get("CBS_FIXTURE", "engine2_constants.json")
C = json.load(open(os.path.join(ROOT, "oracle/fixtures", FIX)))
CH = ["ryth", "vesper_vale", "vendetta", "cassi", "issac", "stellar", "prism", "marcella", "willow", "ren", "varg", "tavi", "heart_of_ruin"]
CA = ["wolf", "elk", "gem_cluster", "gold_cluster", "monolith", "golem"]
REWARD = {"wolf": (40, 4, 40), "elk": (90, 15, 60), "golem": (160, 36, 80), "gem_cluster": (0, 7, 50), "gold_cluster": (20, 0, 50), "monolith": (300, 200, 150)}
KINDS = ["none", "attack_reset", "damage", "aoe_damage", "cc", "heal", "dash", "shield"]
PASS = ["none", "bonus_gold", "remote_shop", "gem_focus", "splash_attack", "health_strength", "reset_cooldowns_on_kill", "retaliation", "stun_immunity", "omnivamp_retired", "missing_health_damage"]

def f(x):
    # exact float32 literal
    return float.hex(struct.unpack("f", struct.pack("f", x))[0]) + "f"

def ability(a):
    k = a["kind"]
    return ("AbilityDesign{AbilityKind::%s, %d, %du, %s, %s, %s, %s, %d, %s}" % (
        k, a["cooldown"], a["targets"], "true" if a["attributes"] & 1 else "false",
        f(a.get("range", 0.0)), f(a.get("radius", 0.0)), f(a.get("modifier", 0.0)), a.get("duration", 0),
        "true" if a.get("enhanced_attack", 0) else "false"))

out = ["// Generated by sim/tools/gen_constants.py from oracle/fixtures/%s. Do not edit." % FIX,
       '#include "cbs/core.h"', "namespace cbs", "{", "namespace", "{"]
out.append("const ChampionDesign kChampions[] = {")
for n in CH:
    c = C["champions"][n]; s = c["stats"]
    out.append("\t{Passive::%s, %s, %d, %d, %d, %s, %s, %s, %s, %s, %s, %s, {%s, %s}}, // %s" % (
        PASS[c["passive"]], "true" if c["attack_type"] == 1 else "false", s["vision_radius"], s["base_move_speed"],
        s["base_attack_range"], f(s["base_health"]), f(s["health_growth"]), f(s["base_strength"]), f(s["strength_growth"]),
        f(s["base_focus"]), f(s["focus_growth"]), f(s["camp_damage_multiplier"]), ability(c["abilities"][0]), ability(c["abilities"][1]), n))
out.append("};")
out.append("const CampDesign kCamps[] = {")
for n in CA:
    c = C["camps"][n]; s = c["stats"]; g, gm, r = REWARD[n]
    out.append("\t{%s, %d, %d, %s, %s, %s, %d, %d, %d, %d}, // %s" % (f(s["vision_radius"]), s["base_move_speed"], s["base_attack_range"],
        f(s["base_health"]), f(s["base_strength"]), f(s["base_focus"]), g, gm, r, c["abilities"][0]["cooldown"], n))
out.append("};")
IP = ["none", "monster", "durability", "treasure", "jungle", "home", "tribute", "capture", "prospector", "hunter", "skirmish", "collectors"]
out.append("const ItemDesign kItems[] = {")
for i in range(len(C["items"])):
    it = C["items"][str(i)]
    out.append("\t{%d, %s, %d, %d, %d, ItemPassive::%s, %s, %d, %d, %d}," % (it["cost"], "true" if it["purchasable"] else "false",
        it["health_points"], it["strength_points"], it["focus_points"], IP[it["passive"]], f(it["passive_magnitude"]),
        it["combine_count"], it["result"] if it["result"] != 255 else -1, it["combine_cost"]))
out.append("};")
out.append("const ConsumableDesign kConsumables[] = {")
for i in range(4):
    c = C["consumables"][str(i)]
    out.append("\t{%d, %d}," % (c["cost"], c["carry_limit"]))
out.append("};")
st = C["settings"]
out.append("const Settings kSettings = [] {")
out.append("\tSettings s;")
for k, v in st.items():
    if k == "reserved": continue
    out.append("\ts.%s = %s;" % (k, f(v) if isinstance(v, float) and k != "submit_gem_duration_multiplier" else repr(v)))
out.append("\treturn s;")
out.append("}();")
out += ["} // namespace",
        "const ChampionDesign& champion_design(ChampionType t) { return kChampions[static_cast<int>(t)]; }",
        "const CampDesign& camp_design(CampType t) { return kCamps[static_cast<int>(t)]; }",
        "const ItemDesign& item_design(int item) { return kItems[item]; }",
        "const ConsumableDesign& consumable_design(int c) { return kConsumables[c]; }",
        "const Settings& settings() { return kSettings; }",
        "} // namespace cbs", ""]
open(os.path.join(ROOT, "sim/src/constants_gen.cpp"), "w").write("\n".join(out))
